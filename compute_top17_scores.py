def calc_q(de, pledge, cfo_pat):
    q_de = max(0.0, 1.0 - (de / 0.50))
    q_pl = max(0.0, 1.0 - (pledge / 10.0))
    q_cf = min(1.0, max(0.0, cfo_pat / 1.0))
    return round(0.50 + 0.50 * (0.35 * q_de + 0.35 * q_pl + 0.30 * q_cf), 4)

def normalize_rc(bm):
    return min(1.0, max(0.0, math.log2(max(bm, 0.01)) / 3.0))

for s in candidates:
    q = calc_q(s['de'], s['pledge'], s['cfo_pat'])
    mb_n = s['mb_raw'] / 100.0
    om = s['omega']
    pot = min(1.0, max(0.01, mb_n * (om ** 0.10)))
    tim = min(1.0, max(0.01, s['tbqe_raw']))
    rc_n = normalize_rc(s['base_multiple'])
    ceil_f = min(1.0, max(0.05, rc_n))
    
    cp = (pot ** 0.55) * (tim ** 0.30) * (ceil_f ** 0.15)
    score = round(100.0 * cp * q, 2)
    s['q'] = q
    s['score'] = score
    s['rc_norm'] = round(rc_n, 2)

candidates.sort(key=lambda x: x['score'], reverse=True)
