class ScreenerCloudConnector:
    """Connects to exchange / cloud endpoints to manage company fundamentals."""

    @staticmethod
    def seed_universe() -> int:
        """Seed SQLite company_fundamentals table with fundamental dataset."""
        conn = get_connection()
        count = 0
        now_iso = datetime.now(timezone.utc).isoformat()
        try:
            for item in _SEED_UNIVERSAL_FUNDAMENTALS:
                conn.execute(
                    """INSERT OR REPLACE INTO company_fundamentals 
                       (symbol, company_name, market_cap, current_price, volume, high_52w, low_52w, roe_3yr, roe_latest, roce_3yr, roce_latest, opm_5yr, opm_latest, operating_profit, op_growth, pat_growth_3yr, pat_growth_latest, sales_growth_3yr, sales_growth_latest, eps_growth_3yr, eps_latest, cfo_3yr, net_block, net_block_3yr_back, net_block_preceding_year, cwip, cwip_preceding_year, cfo_last_year, net_profit_last_year, vol_1w_avg, vol_1m_avg, vol_1y_avg, piotroski_score, promoter_holding, pledged_pct, debt_to_equity, interest_coverage, peg_ratio, updated_at)
                       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                    (
                        item["symbol"],
                        item["company_name"],
                        item["market_cap"],
                        item["current_price"],
                        item["volume"],
                        item["high_52w"],
                        item["low_52w"],
                        item["roe_3yr"],
                        item["roe_latest"],
                        item["roce_3yr"],
                        item["roce_latest"],
                        item["opm_5yr"],
                        item["opm_latest"],
                        item["operating_profit"],
                        item["op_growth"],
                        item["pat_growth_3yr"],
                        item["pat_growth_latest"],
                        item["sales_growth_3yr"],
                        item["sales_growth_latest"],
                        item["eps_growth_3yr"],
                        item["eps_latest"],
                        item["cfo_3yr"],
                        item.get("net_block", 0.0),
                        item.get("net_block_3yr_back", 0.0),
                        item.get("net_block_preceding_year", 0.0),
                        item.get("cwip", 0.0),
                        item.get("cwip_preceding_year", 0.0),
                        item.get("cfo_last_year", 0.0),
                        item.get("net_profit_last_year", 0.0),
                        item.get("vol_1w_avg", 0.0),
                        item.get("vol_1m_avg", 0.0),
                        item.get("vol_1y_avg", 0.0),
                        item.get("piotroski_score", 0.0),
                        item.get("promoter_holding", 0.0),
                        item.get("pledged_pct", 0.0),
                        item.get("debt_to_equity", 0.0),
                        item.get("interest_coverage", 0.0),
                        item.get("peg_ratio", 0.0),
                        now_iso
                    )
                )
                count += 1
            conn.commit()
        finally:
            conn.close()
        return count

    @staticmethod
    def get_all_fundamentals() -> List[Dict[str, Any]]:
        """Fetch all stored company fundamentals from SQLite."""
        ScreenerCloudConnector.seed_universe()
        conn = get_connection()
        try:
            rows = conn.execute("SELECT * FROM company_fundamentals").fetchall()
            return [dict(r) for r in rows]
        finally:
            conn.close()
